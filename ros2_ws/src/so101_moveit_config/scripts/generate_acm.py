#!/usr/bin/env python3
"""Find link pairs that never collide (or always do), like the MoveIt Setup Assistant does.

Run while move_group is running with only the 'Adjacent' pairs disabled:
    ros2 run so101_moveit_config generate_acm.py --samples 2000
Prints <disable_collisions> lines to paste into config/so101.srdf.
"""
import argparse
import itertools
import random

import rclpy
from moveit_msgs.msg import RobotState
from moveit_msgs.srv import GetStateValidity
from rclpy.node import Node
from sensor_msgs.msg import JointState

JOINTS = {"shoulder_pan": (-1.91986, 1.91986), "shoulder_lift": (-1.74533, 1.74533),
          "elbow_flex": (-1.69, 1.69), "wrist_flex": (-1.65806, 1.65806),
          "wrist_roll": (-2.74385, 2.84121), "gripper": (-0.174533, 1.74533)}
LINKS = ["base_link", "shoulder_link", "upper_arm_link", "lower_arm_link", "wrist_link",
         "gripper_link", "moving_jaw_so101_v1_link"]
ADJACENT = {frozenset(p) for p in zip(LINKS[:-2], LINKS[1:-1])} | {frozenset(("gripper_link", "moving_jaw_so101_v1_link"))}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--samples", type=int, default=2000)
    a = ap.parse_args()
    rclpy.init()
    node = Node("generate_acm")
    cli = node.create_client(GetStateValidity, "/check_state_validity")
    cli.wait_for_service(timeout_sec=10.0)
    counts = {frozenset(p): 0 for p in itertools.combinations(LINKS, 2)}
    rng = random.Random(0)
    for _ in range(a.samples):
        js = JointState(name=list(JOINTS), position=[rng.uniform(*r) for r in JOINTS.values()])
        req = GetStateValidity.Request(robot_state=RobotState(joint_state=js), group_name="arm")
        fut = cli.call_async(req)
        rclpy.spin_until_future_complete(node, fut)
        seen = {frozenset((c.contact_body_1, c.contact_body_2)) for c in fut.result().contacts}
        for p in seen:
            if p in counts:
                counts[p] += 1
    print("<!-- generated by generate_acm.py from", a.samples, "random states -->")
    for p, n in sorted(counts.items(), key=lambda kv: sorted(kv[0])):
        if p in ADJACENT:
            continue
        l1, l2 = sorted(p)
        if n == 0:
            print(f'  <disable_collisions link1="{l1}" link2="{l2}" reason="Never"/>')
        elif n >= 0.95 * a.samples:
            print(f'  <disable_collisions link1="{l1}" link2="{l2}" reason="Default"/>')
        else:
            print(f'  <!-- checked: {l1} / {l2} collide in {100 * n / a.samples:.1f} % of states -->')
    node.destroy_node()
    rclpy.shutdown()


if __name__ == "__main__":
    main()
